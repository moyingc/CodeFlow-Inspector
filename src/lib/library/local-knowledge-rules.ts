export const localKnowledgeRules: KnowledgeRule[] = [
  ...baseLocalKnowledgeRules,
  ...localKnowledgeGapFillRules,
  ...localKnowledgeExtendedRules,
];

export const localLanguageApiRules: LanguageApiRule[] = localKnowledgeRules
  .filter((rule) => rule.category === "language_api")
  .map((rule) => ({
    id: `api-${rule.id}`,
    language: rule.language ?? "unknown",
    module: moduleFromRule(rule),
    apiName: rule.name,
    signature: rule.inputs.join(", "),
    behavior: rule.summary,
    returns: rule.outputs.join(", "),
    riskTags: rule.tags,
    safeAlternative: rule.safeAlternative ?? rule.recommendation,
    sourceVersionId: rule.sourceVersionId,
  }));

export const localKnowledgeRuleEvidence: KnowledgeRuleEvidence[] = localKnowledgeRules.flatMap((rule) =>
  buildEvidenceForRule(rule),
);

export function knowledgeRuleCountByCategory(category: KnowledgeRuleCategory) {
  return localKnowledgeRules.filter((rule) => rule.category === category).length;
}

export function knowledgeRuleCountByLibraryCategory(category: LocalLibraryCategory) {
  const ruleCategory = ruleCategoryForLibraryCategory(category);
  return ruleCategory ? knowledgeRuleCountByCategory(ruleCategory) : 0;
}

export function ruleCategoryForLibraryCategory(category: LocalLibraryCategory): KnowledgeRuleCategory | null {
  const map: Partial<Record<LocalLibraryCategory, KnowledgeRuleCategory>> = {
    数学模型库: "math",
    算法模型库: "algorithm",
    效率知识库: "efficiency",
    安全规则库: "security",
    稳定性规则库: "stability",
    语言生态库: "language_api",
  };
  return map[category] ?? null;
}

function moduleFromRule(rule: KnowledgeRule) {
  if (rule.id.includes("node-readfile")) return "node:fs";
  if (rule.id.includes("node-exec")) return "node:child_process";
  if (rule.id.includes("python-subprocess")) return "subprocess";
  if (rule.id.includes("python-open")) return "builtins";
  if (rule.id.includes("python-requests")) return "requests";
  if (rule.id.includes("python-pickle")) return "pickle";
  if (rule.id.includes("java-runtime")) return "java.lang";
  if (rule.id.includes("java-sql")) return "java.sql";
  if (rule.id.includes("java-objectinputstream")) return "java.io";
  if (rule.id.includes("c-strcpy")) return "libc/string";
  if (rule.id.includes("c-system")) return "libc/stdlib";
  if (rule.id.includes("cpp-raw-pointer")) return "C++ memory";
  if (rule.id.includes("prisma")) return "Prisma";
  if (rule.id.includes("sqlalchemy")) return "SQLAlchemy";
  if (rule.id.includes("spring")) return "Spring MVC";
  if (rule.id.includes("express-cors")) return "Express";
  if (rule.id.includes("arduino")) return "Arduino Serial";
  if (rule.id.includes("dom-innerhtml")) return "DOM";
  if (rule.id.includes("js-json-parse")) return "JSON";
  if (rule.id.includes("go-exec")) return "os/exec";
  if (rule.id.includes("rust-unwrap")) return "Result/Option";
  if (rule.id.includes("fetch")) return "Web API";
  return "standard library";
}

function buildEvidenceForRule(rule: KnowledgeRule): KnowledgeRuleEvidence[] {
  const baseEvidence: KnowledgeRuleEvidence = {
    id: `evidence-${rule.id}-static`,
    ruleId: rule.id,
    evidenceType: rule.category === "security" ? "regex" : rule.category === "language_api" ? "ast" : "type",
    matcher: rule.signalPatterns.join(" | "),
    weight: rule.confidenceBase,
    positiveExample: rule.signalPatterns[0] ?? rule.name,
    negativeExample: "未命中该信号或存在明确 guard。",
  };
  const extraEvidence: KnowledgeRuleEvidence[] = [];

  if (rule.appliesTo.includes("runtimeSandbox") || rule.tags.some((tag) => ["timeout", "retry", "concurrency", "memory"].includes(tag))) {
    extraEvidence.push({
      id: `evidence-${rule.id}-runtime`,
      ruleId: rule.id,
      evidenceType: "runtime",
      matcher: `scenario.status matches ${rule.outputs.join("|")}`,
      weight: Math.max(0.5, rule.confidenceBase - 0.08),
      positiveExample: "仿真样本触发超时、资源峰值、阻塞或异常出口。",
      negativeExample: "仿真样本在资源预算内稳定通过。",
    });
  }

  if (rule.category === "language_api" || rule.tags.some((tag) => ["node", "python", "go", "rust", "database"].includes(tag))) {
    extraEvidence.push({
      id: `evidence-${rule.id}-dependency`,
      ruleId: rule.id,
      evidenceType: "dependency",
      matcher: `language=${rule.language ?? "unknown"} api=${rule.name}`,
      weight: Math.max(0.5, rule.confidenceBase - 0.06),
      positiveExample: "项目依赖或语言包版本包含该 API 行为。",
      negativeExample: "当前语言、运行时或依赖版本不适用该 API。",
    });
  }

  return [baseEvidence, ...extraEvidence];
}
